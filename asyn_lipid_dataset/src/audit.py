#!/usr/bin/env python3
"""Audit the dataset and build the 8-candidate evidence table.

Writes:
  outputs/audit_report.md
  outputs/candidate_evidence_table.csv  (+ .md)

Reports counts of papers, lipids, conditions, measurements by endpoint/evidence,
raw-vs-digitized, candidate coverage, missingness, matched-control availability.
Independent-experiment counting is conservative: one condition = one experiment;
replicate wells and time points are NOT counted as independent.
"""
import csv
import os
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "outputs")
os.makedirs(OUT, exist_ok=True)


def load(name):
    return list(csv.DictReader(open(os.path.join(DATA, name))))


papers = load("papers.csv")
conds = load("conditions.csv")
comps = load("components.csv")
meas = load("measurements.csv")
lipids = load("lipids.csv")

cond_by_id = {c["condition_id"]: c for c in conds}
comps_by_cond = defaultdict(list)
for c in comps:
    comps_by_cond[c["condition_id"]].append(c)
meas_by_cond = defaultdict(list)
for m in meas:
    meas_by_cond[m["condition_id"]].append(m)

CANDIDATES = ["Cholesterol", "SM", "DMPC", "DPPC", "DSPC", "DOPC", "POPC", "GM1"]
CAND_DISPLAY = {"SM": "Sphingomyelin (SM)"}

L = []
def p(s=""):
    L.append(s)

p("# Dataset audit report")
p()
p("_Auto-generated by `src/audit.py`. Independent-experiment counting is conservative: "
  "one experimental **condition** = one experiment; replicate wells and time points are NOT "
  "counted as independent experiments._")
p()

# ---- headline counts ----
primary = [pp for pp in papers if pp["role"].startswith("primary")]
p("## 1. Headline counts")
p()
p(f"- Papers total: **{len(papers)}** (primary aggregation/support: "
  f"**{len([pp for pp in papers if pp['role'] in ('primary_aggregation','primary_support')])}**, "
  f"assay reference: {len([pp for pp in papers if pp['role']=='assay_reference'])})")
p(f"- Papers with full text accessed: **{len([pp for pp in papers if pp['access_status']=='full_text'])}**; "
  f"abstract-only: **{len([pp for pp in papers if pp['access_status']=='abstract_only'])}** "
  f"({', '.join(pp['paper_id'] for pp in papers if pp['access_status']=='abstract_only')})")
p(f"- Unique lipids/components catalogued: **{len(lipids)}** "
  f"(defined SMILES: {len([l for l in lipids if l['smiles_valid']=='ok'])}, "
  f"natural mixtures/omitted: {len([l for l in lipids if l['natural_mixture']=='1'])})")
p(f"- Experimental conditions: **{len(conds)}**")
p(f"- Measurement records: **{len(meas)}**")
p()

# unique formulations (distinct component-set signatures)
def formulation_sig(cid):
    cs = comps_by_cond[cid]
    return tuple(sorted((c["lipid_id"], str(c["mol_fraction"])) for c in cs))
uniq_forms = set(formulation_sig(c["condition_id"]) for c in conds if comps_by_cond[c["condition_id"]])
p(f"- Distinct lipid formulations (by component/fraction signature): **{len(uniq_forms)}**")
p()

# ---- measurements by endpoint / evidence ----
p("## 2. Measurements by endpoint and evidence")
p()
p("By evidence category:")
for k, v in Counter(m["evidence_category"] for m in meas).most_common():
    p(f"  - {k}: {v}")
p()
p("By evidence type (raw/text vs digitized vs qualitative):")
for k, v in Counter(m["evidence_type"] for m in meas).most_common():
    p(f"  - {k}: {v}")
p()
p("By endpoint:")
for k, v in Counter(m["endpoint"] for m in meas).most_common():
    p(f"  - {k}: {v}")
p()
direct = [m for m in meas if m["evidence_category"] == "direct_aggregation"]
p(f"Direct-aggregation effect-direction labels (n={len(direct)}):")
for k, v in Counter(m["effect_direction"] for m in direct).most_common():
    p(f"  - {k}: {v}")
p()
p(f"- Digitized numeric observations currently in dataset: "
  f"**{len([m for m in meas if m['evidence_type']=='digitized' and m['quality_flag']!='digitization_pending'])}** "
  f"(curves marked `digitization_pending`: {len([m for m in meas if m['quality_flag']=='digitization_pending'])})")
p()

# ---- by paper ----
p("## 3. Conditions and measurements per paper")
p()
p("| paper | conditions | direct-agg measurements | assay paradigm | pH | plate |")
p("|---|---|---|---|---|---|")
for pp in papers:
    pid = pp["paper_id"]
    cs = [c for c in conds if c["paper_id"] == pid]
    if not cs:
        continue
    dm = [m for m in meas if m["paper_id"] == pid and m["evidence_category"] == "direct_aggregation"]
    paradigms = sorted(set(c["assay_paradigm"] for c in cs if c["assay_paradigm"]))
    phs = sorted(set(c["pH"] for c in cs if c["pH"]))
    plates = sorted(set((c["plate"] or "?")[:20] for c in cs if c["formulation"] != "none"))
    p(f"| {pid} | {len(cs)} | {len(dm)} | {','.join(paradigms)} | {','.join(map(str,phs)) or '?'} | "
      f"{'; '.join(plates)[:40]} |")
p()

# ---- matched controls ----
p("## 4. Matched controls")
p()
with_ctrl = [m for m in direct if m["control_id"]]
ctrl_exists = [m for m in with_ctrl if m["control_id"] in cond_by_id]
p(f"- Direct-aggregation measurements that name a matched control: **{len(with_ctrl)}/{len(direct)}**")
p(f"- Of those, control condition present in dataset: **{len(ctrl_exists)}/{len(with_ctrl)}**")
missing_ctrl = set(m["control_id"] for m in with_ctrl if m["control_id"] not in cond_by_id)
if missing_ctrl:
    p(f"- Named controls not (yet) present as conditions: {sorted(missing_ctrl)}")
p()

# ---- missingness in key condition fields ----
p("## 5. Missingness in key experimental conditions")
p()
key_fields = ["protein_conc_uM", "pH", "temp_C", "agitation", "plate", "tht_uM",
              "total_lipid_uM", "lipid_to_protein_molar_ratio"]
p("| field | conditions with value | missing |")
p("|---|---|---|")
for f in key_fields:
    have = sum(1 for c in conds if str(c.get(f, "")).strip() not in ("", "?"))
    p(f"| {f} | {have}/{len(conds)} | {len(conds)-have} |")
p()
p("_Note: concentrations/ratios are intentionally blank where a paper reported only a "
  "range or did not report a numeric value (e.g. Martinez 2007 abstract-only; Galvagnion "
  "mixture experiments reported as ratios). Missing values are explicit, never imputed._")
p()

# ---- candidate coverage ----
p("## 6. Coverage of the 8 wet-lab candidates")
p()
p("A condition is counted as **primary** for a candidate when that candidate is the only lipid "
  "or the dominant (non-matrix) driver, and as **matrix/additive** when the candidate is only the "
  "background lipid (e.g. DOPC carrying 10% GM1) or a minor additive. Effect directions are reported "
  "for the **primary** conditions only, because that is where the candidate's own effect is observable.")
p()
p("| candidate | primary conds | matrix/additive conds | papers | effect directions (primary) |")
p("|---|---|---|---|---|")

# The lipid "being studied" (driver) in a condition is the charged / special component, or
# the sole lipid. A zwitterionic PC 'main' lipid in a mixture that also contains a charged/
# special component is just the inert background matrix.
DRIVER_ROLES = {"anionic", "cationic", "sterol_additive", "neutral_large_head",
                "natural_extract", "exosome"}

def candidate_role(cand, cond):
    """Classify the candidate's role: 'primary' (the studied driver) or 'matrix'."""
    cs = comps_by_cond[cond["condition_id"]]
    mine = [c for c in cs if c["lipid_id"] == cand]
    if not mine:
        return None
    if len(cs) == 1:
        return "primary"  # pure single-lipid system
    my_roles = set(c["role"] for c in mine)
    if my_roles & DRIVER_ROLES:
        return "primary"  # candidate is the charged/special component being studied
    # candidate is a 'main' lipid in a mixture; it is the driver only if NO other
    # component carries a driver role (otherwise it is the inert matrix)
    others_driver = any(c["role"] in DRIVER_ROLES for c in cs if c["lipid_id"] != cand)
    return "matrix" if others_driver else "primary"

cand_rows_for_table = {}
for cand in CANDIDATES:
    cand_conds = [c for c in conds if any(cp["lipid_id"] == cand for cp in comps_by_cond[c["condition_id"]])]
    prim = [c for c in cand_conds if candidate_role(cand, c) == "primary"]
    nonprim = [c for c in cand_conds if candidate_role(cand, c) in ("matrix", "additive")]
    cand_papers = sorted(set(c["paper_id"] for c in cand_conds))
    dirs = Counter()
    for c in prim:
        for m in meas_by_cond[c["condition_id"]]:
            if m["evidence_category"] == "direct_aggregation" and m["effect_direction"] not in ("", "not_applicable"):
                dirs[m["effect_direction"]] += 1
    cand_rows_for_table[cand] = (cand_conds, prim, nonprim, cand_papers, dirs)
    disp = CAND_DISPLAY.get(cand, cand)
    p(f"| {disp} | {len(prim)} | {len(nonprim)} | {', '.join(cand_papers) or '—'} | "
      f"{', '.join(f'{k}×{v}' for k,v in dirs.most_common()) or '— (candidate never the primary driver)'} |")
p()
p("_DOPC is the standard zwitterionic matrix in Grey & Gaspar, so most of its appearances are as a "
  "background bilayer carrying an anionic additive; only its **pure** conditions (retardation / no effect) "
  "reflect DOPC's own behaviour. GM1 is a genuine additive/driver in every appearance._")
p()

# ---- write markdown report ----
open(os.path.join(OUT, "audit_report.md"), "w").write("\n".join(L))
print("wrote outputs/audit_report.md")

# ---- 8-candidate evidence table (CSV + MD) ----
ev_fields = ["candidate", "lipid_class", "direct_evidence_found", "n_conditions", "papers",
             "formulations_conditions_tested", "effect_direction_summary",
             "conflicting_findings", "quantitative_prediction_supported", "notes_for_assay"]
ev_rows = []

# curated per-candidate synthesis (grounded in the extracted records)
